"""Report formatters for ACE-U identity assessments."""
import json
from typing import Any

from . import HOMEPAGE


def to_json(results: list[dict[str, Any]]) -> str:
    return json.dumps({"schemaVersion": "1.0", "informationUri": HOMEPAGE, "results": results}, indent=2) + "\n"


def to_markdown(results: list[dict[str, Any]]) -> str:
    lines = ["# ACE-U Entra Trust Report", "", f"[Project homepage]({HOMEPAGE})", "", "| Identity | Score | Band | A | U | C |", "|---|---:|---|---:|---:|---:|"]
    for result in results:
        scores = result["scores"]
        lines.append(f"| {result['displayName']} ({result['id']}) | {result['total']} | {result['band']} | {scores['Authenticity']} | {scores['Uniqueness']} | {scores['Credibility']} |")
        for finding in result["findings"]:
            lines.append(f"  - **{finding['id']}** ({finding['severity']}): {finding['message']}")
    lines += ["", f"Generated by [aceu-entra-trust]({HOMEPAGE}). Read-only assessment.", ""]
    return "\n".join(lines)


def to_sarif(results: list[dict[str, Any]]) -> str:
    rules, seen, sarif_results = [], set(), []
    severity = {"high": "error", "medium": "warning", "low": "note", "info": "note"}
    for item in results:
        for finding in item["findings"]:
            if finding["id"] not in seen:
                seen.add(finding["id"])
                rules.append({"id": finding["id"], "shortDescription": {"text": finding["message"]}, "helpUri": HOMEPAGE})
            sarif_results.append({"ruleId": finding["id"], "level": severity[finding["severity"]], "message": {"text": f"{item['displayName']} ({item['id']}): {finding['message']}"}, "properties": {"pillar": finding["pillar"], "penalty": finding["penalty"]}})
    return json.dumps({"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0", "runs": [{"tool": {"driver": {"name": "aceu-entra-trust", "informationUri": HOMEPAGE, "rules": rules}}, "results": sarif_results}]}, indent=2) + "\n"
